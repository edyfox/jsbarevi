#!/usr/bin/env node
// Write src/build-info.js with the current commit, so a cached page is
// distinguishable from a broken one: the UI prints this string.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
let sha = "nogit";
try { sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim(); } catch {}
let dirty = "";
try { dirty = execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], { cwd: ROOT, encoding: "utf8" }).trim() ? "+dirty" : ""; } catch {}
const stamp = `${sha}${dirty}`;
const out = `// generated by tools/stamp-build.mjs — do not edit\nexport const BUILD = ${JSON.stringify(stamp)};\nexport const BUILD_AT = ${JSON.stringify(new Date().toISOString())};\n`;
fs.writeFileSync(path.join(ROOT, "src/build-info.js"), out);
console.log("build stamp:", stamp);
