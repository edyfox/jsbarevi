// The build identity: ONE definition of "which code is this?", used by the stamp
// script, by the dev server (which serves it at request time) and by anything that
// packages the extension.
//
// Why it is a module and not five lines inside the stamp script: the value has to
// describe the code the BROWSER actually loaded. A file stamped before a commit
// describes the previous commit forever - which is a stale label on a current page,
// the exact confusion the label exists to prevent.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Parse a `git status --porcelain` listing into a dirty flag. The generated stamp
 * file is excluded, otherwise the act of stamping would make the tree dirty and
 * every stamp after the first would say "+dirty".
 */
export function isDirty(statusText) {
  return statusText
    .split("\n")
    .map((line) => line.slice(3).trim())
    .filter(Boolean)
    .some((file) => file !== "src/build-info.js");
}

/** The release semver, read from the same `package.json` the manifest is stamped
 *  from. It lives here so no source file can hard-code a semver of its own: the
 *  extension printed `0.1.0+<commit>` for five releases because `src/entry.js`
 *  carried its own literal, which made a current build label itself as a stale one. */
export function releaseVersion(cwd = process.cwd()) {
  try {
    return JSON.parse(readFileSync(path.join(cwd, "package.json"), "utf8")).version || "0.0.0";
  } catch {
    return "0.0.0";
  }
}

/** { sha, dirty, stamp, at, version } for the checkout at `cwd`. */
export function currentBuild({ cwd = process.cwd() } = {}) {
  let sha = "nogit";
  try {
    sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd, encoding: "utf8" }).trim();
  } catch { /* not a checkout */ }
  let statusText = "";
  try {
    statusText = execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], { cwd, encoding: "utf8" });
  } catch { /* not a checkout */ }
  const dirty = sha !== "nogit" && isDirty(statusText);
  return { sha, dirty, stamp: `${sha}${dirty ? "+dirty" : ""}`, at: new Date().toISOString(), version: releaseVersion(cwd) };
}

/** The module source for src/build-info.js. */
export function buildInfoSource(build) {
  // Generated and NOT tracked (see .gitignore). A committed copy could only ever name the
  // parent commit — this file is written before the commit that contains it — so tracking
  // it dirtied the tree on every build to record a label the README calls out as false.
  // The dev server replaces it per request; the on-disk copy exists for a plain static serve.
  return `// generated by tools/build-id.mjs — do not edit, not tracked\n`
    + `// (the dev server serves this live from git; this file is for a plain static serve)\n`
    + `export const BUILD = ${JSON.stringify(build.stamp)};\n`
    + `export const BUILD_AT = ${JSON.stringify(build.at)};\n`
    + `export const VERSION = ${JSON.stringify(build.version || "0.0.0")};\n`;
}

export const buildInfoPath = (root) => path.join(root, "src", "build-info.js");
