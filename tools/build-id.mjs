// The build identity: ONE definition of "which code is this?", used by the stamp
// script, by the dev server (which serves it at request time) and by anything that
// packages the extension.
//
// Why it is a module and not five lines inside the stamp script: the value has to
// describe the code the BROWSER actually loaded. A file stamped before a commit
// describes the previous commit forever - which is a stale label on a current page,
// the exact confusion the label exists to prevent.
import { execFileSync } from "node:child_process";
import path from "node:path";

/**
 * Parse a `git status --porcelain` listing into a dirty flag. The generated stamp
 * file is excluded, otherwise the act of stamping would make the tree dirty and
 * every stamp after the first would say "+dirty".
 */
export function isDirty(statusText) {
  return statusText
    .split("\n")
    .map((line) => line.slice(3).trim())
    .filter(Boolean)
    .some((file) => file !== "src/build-info.js");
}

/** { sha, dirty, stamp, at } for the checkout at `cwd`. */
export function currentBuild({ cwd = process.cwd() } = {}) {
  let sha = "nogit";
  try {
    sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd, encoding: "utf8" }).trim();
  } catch { /* not a checkout */ }
  let statusText = "";
  try {
    statusText = execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], { cwd, encoding: "utf8" });
  } catch { /* not a checkout */ }
  const dirty = sha !== "nogit" && isDirty(statusText);
  return { sha, dirty, stamp: `${sha}${dirty ? "+dirty" : ""}`, at: new Date().toISOString() };
}

/** The module source for src/build-info.js. */
export function buildInfoSource(build) {
  return `// generated by tools/build-id.mjs — do not edit\n`
    + `export const BUILD = ${JSON.stringify(build.stamp)};\n`
    + `export const BUILD_AT = ${JSON.stringify(build.at)};\n`;
}

export const buildInfoPath = (root) => path.join(root, "src", "build-info.js");
